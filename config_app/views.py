@csrf_exempt
def create_config_view(request):
    if request.method == 'POST':
        try:
            # Проверяем, является ли запрос multipart/form-data (с файлами)
            if request.content_type.startswith('multipart/form-data'):
                # Обработка запроса с файлом
                if 'file' not in request.FILES:
                    return JsonResponse({'error': 'File is required'}, status=400)
                
                uploaded_file = request.FILES['file']
                
                # Проверяем, что это zip-файл
                if not uploaded_file.name.endswith('.zip'):
                    return JsonResponse({'error': 'Only zip files are allowed'}, status=400)
                
                # Получаем prompt из POST данных
                prompt = request.POST.get('prompt', '')
                if not prompt:
                    return JsonResponse({'error': 'Prompt is required'}, status=400)
                
                # Получаем другие параметры из POST данных
                name = request.POST.get('name', 'Generated Config')
                description = request.POST.get('description', 'Configuration generated by AI')
                
                # Валидация meta_config
                vcs_type = request.POST.get('vcs_type', 'github')
                temperature = float(request.POST.get('temperature', 0.5))
                
                # Сохраняем временно файл
                import os
                from django.conf import settings
                
                upload_dir = os.path.join(settings.MEDIA_ROOT, 'temp')
                os.makedirs(upload_dir, exist_ok=True)
                
                temp_file_path = os.path.join(upload_dir, uploaded_file.name)
                with open(temp_file_path, 'wb+') as destination:
                    for chunk in uploaded_file.chunks():
                        destination.write(chunk)
                
                # Обрабатываем файл с помощью ИИ
                from .ai_client import AIClient
                ai_client = AIClient()
                ai_result = ai_client.process_config_request(temp_file_path, prompt)
                
                # Удаляем временный файл
                os.remove(temp_file_path)
                
                if not ai_result['success']:
                    return JsonResponse({'error': ai_result['content']}, status=500)
                
                # Создание или получение MetaConfig
                meta_config = MetaConfig.objects.create(
                    vcs_type=vcs_type,
                    temperature=temperature
                )

                # Создание NewConfig
                new_config = NewConfig.objects.create(
                    name=name,
                    description=description,
                    files=ai_result['file_structure'],  # Используем структуру файлов из ИИ
                    meta_config=meta_config
                )
                
                # Создаем сообщение от ИИ
                ai_message = Message.objects.create(
                    author='model',
                    content=ai_result['content'],
                    files=[],  # Пока пустой список, можно добавить файлы, если ИИ возвращает
                    config=new_config
                )
                
                return JsonResponse({
                    'message': 'Configuration created successfully',
                    'config_id': new_config.id,
                    'ai_response': ai_result['content'],
                    'file_structure': ai_result['file_structure']
                })
            else:
                # Обработка обычного JSON-запроса
                data = json.loads(request.body)

                # Валидация обязательных полей
                required_fields = ['name', 'description', 'files', 'meta_config']
                for field in required_fields:
                    if field not in data:
                        return JsonResponse({'error': f'{field} is required'}, status=400)

                # Создание или получение MetaConfig
                meta_config_data = data['meta_config']
                meta_config = MetaConfig.objects.create(
                    vcs_type=meta_config_data['vcs_type'],
                    temperature=meta_config_data['temperature']
                )

                # Создание NewConfig
                new_config = NewConfig.objects.create(
                    name=data['name'],
                    description=data['description'],
                    files=data['files'],
                    meta_config=meta_config
                )

                return JsonResponse({
                    'message': 'Configuration created successfully',
                    'config_id': new_config.id
                })
        except json.JSONDecodeError:
            return JsonResponse({'error': 'Invalid JSON'}, status=400)
        except KeyError as e:
            return JsonResponse({'error': f'Missing required field: {str(e)}'}, status=400)
        except Exception as e:
            return JsonResponse({'error': str(e)}, status=500)
    else:
        return JsonResponse({'error': 'Only POST method allowed'}, status=405)


